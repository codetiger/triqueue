"""Design-space sweep over tile size T (and port width W) with the cycle model.

Run: python3 dse.py            (writes dse.md next to this file)
Shapes come from bench/workloads/gemm.csv (tag `dse`). Every run is checked bit-exact against numpy.
"""
import math
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "bench" / "workloads"))
from workloads import shapes  # noqa: E402
from tri_queue.core import run_gemm, reference, Params  # noqa: E402

TILES = (8, 16, 32)
rng = np.random.default_rng(7)
_cache = {}


def gemm(m, n, k, p: Params):
    key = (m, n, k, tuple(sorted(vars(p).items())))
    if key not in _cache:
        a = rng.integers(-128, 128, (m, k)).astype(np.int8)
        b = rng.integers(-128, 128, (k, n)).astype(np.int8)
        c, s = run_gemm(a, b, p)
        assert np.array_equal(c, reference(a, b)), (m, n, k, p)
        _cache[key] = s
    return _cache[key]


def pct(x):
    return f"{100 * x:.1f}%"


MCMD_BITS = 52   # MAC command queue entry in RTL v0 (rtl/core/tq_pkg.sv, MCMD_W)


def state_bits(p: Params):
    """Architectural state in bits (spec section 2.1 generalized to T, W): operand FIFOs, accumulator
    banks, CFG and the MAC command queue. Pipeline registers and the program buffer are excluded."""
    fifos = 2 * p.fifo_depth * p.port_bytes * 8      # QA + QB
    sc = p.banks * p.tile * p.tile * 64               # sum + carry, 32 b each
    cfg = 8 * 32
    macq = p.mac_queue_depth * MCMD_BITS
    return fifos, sc, fifos + sc + cfg + macq


def drain_hidden_kp(p: Params):
    """Smallest Kp (multiple of 8) at which the cycle model shows no wait_drain on a 4x4-tile GEMM."""
    t = p.tile
    for kpad in range(8, 8 * t + 64, 8):
        if gemm(4 * t, 4 * t, kpad, p).mac_state.get("wait_drain", 0) == 0:
            return kpad
    return None


out = []
w = out.append
w("# Tile-size design-space sweep (cycle model)\n")
w("Generated by `model/dse.py`. Every run is also checked bit-exact against numpy. "
  "Defaults otherwise as in `model/results.md`: memory latency 2, FIFO depth 8 vectors, separate write port, 2 banks. "
  "Utilization only: area, power and clock need synthesis.\n")

# 1. configurations
w("## 1. Configurations (W = 2T, balanced port)\n")
w("| T | MACs/cycle | Read port | QA+QB bits | SC bits | Total state | State bits per MAC "
  "| Bytes read per MAC (128³) | Drain writes per tile | Kp that hides the drain |")
w("| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |")
for t in TILES:
    p = Params(tile=t)
    fifos, sc, total = state_bits(p)
    s = gemm(128, 128, 128, p)
    w(f"| {t} | {t * t} | {8 * p.port_bytes} b | {fifos:,} | {sc:,} | {total:,} | {total / (t * t):.0f} "
      f"| {s.read_bytes / s.useful_macs:.4f} | {t * math.ceil(4 * t / p.port_bytes)} | ≥ {drain_hidden_kp(p)} |")
w("")

# 2. workloads
rows = shapes("dse")
w("## 2. Utilization by workload\n")
w("| M×N×K | " + " | ".join(f"T = {t}" for t in TILES) + " |")
w("| --- |" + " --- |" * len(TILES))
util = {t: [] for t in TILES}
for m, n, k in rows:
    cells = []
    for t in TILES:
        u = gemm(m, n, k, Params(tile=t)).utilization
        util[t].append(u)
        cells.append(pct(u))
    w(f"| {m}×{n}×{k} | " + " | ".join(cells) + " |")
w("| **Geometric mean** | " + " | ".join(
    f"**{pct(math.exp(sum(math.log(u) for u in util[t]) / len(util[t])))}**" for t in TILES) + " |")
w("")
w("Useful MACs per cycle (utilization × T²), geometric mean over the same shapes: " + ", ".join(
    f"T = {t}: {t * t * math.exp(sum(math.log(u) for u in util[t]) / len(util[t])):.1f}" for t in TILES) + ".\n")

# 3. drain hiding
w("## 3. Drain hiding vs K (M = N = 4T, 16 tiles)\n")
ks = (8, 16, 32, 64, 128, 256)
w("| T | " + " | ".join(f"K = {k}" for k in ks) + " |")
w("| --- |" + " --- |" * len(ks))
for t in TILES:
    w(f"| {t} | " + " | ".join(pct(gemm(4 * t, 4 * t, k, Params(tile=t)).utilization) for k in ks) + " |")
w("")

# 4. port width
w("## 4. Port width at T = 16 (128×128×128)\n")
w("| Read port | Utilization | Note |")
w("| --- | --- | --- |")
for wb, note in ((16, "half the balanced width"), (32, "balanced (2T bytes)"), (64, "twice the balanced width")):
    s = gemm(128, 128, 128, Params(tile=16, port_bytes=wb))
    w(f"| {8 * wb} b | {pct(s.utilization)} | {note} |")
w("")

# 5. FIFO depth vs latency
w("## 5. FIFO depth needed vs SRAM latency (M = N = 4T, K = 128)\n")
lat = (2, 8, 16)
w("| T | FIFO depth | " + " | ".join(f"latency {x}" for x in lat) + " |")
w("| --- | --- |" + " --- |" * len(lat))
for t in TILES:
    for depth in (4, 8, 16):
        w(f"| {t} | {depth} | " + " | ".join(
            pct(gemm(4 * t, 4 * t, 128, Params(tile=t, fifo_depth=depth, mem_latency=x)).utilization) for x in lat) + " |")
w("")

text = "\n".join(out)
Path(__file__).with_name("dse.md").write_text(text + "\n")
print(text)
