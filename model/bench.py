"""Cycle-model benchmarks for the Tri-Queue core, checked against the spec's predictions.

Run: python3 bench.py            (writes results.md next to this file)
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "bench" / "workloads"))
from workloads import shapes  # noqa: E402

from tri_queue.core import run_gemm, reference, Params  # noqa: E402

rng = np.random.default_rng(42)


def gemm(m, n, k, p=None):
    a = rng.integers(-128, 128, (m, k)).astype(np.int8)
    b = rng.integers(-128, 128, (k, n)).astype(np.int8)
    c, s = run_gemm(a, b, p)
    assert np.array_equal(c, reference(a, b)), (m, n, k)
    return s


def pct(x):
    return f"{100 * x:.1f}%"


def stalls(s):
    keep = {k: v for k, v in s.mac_state.items() if k != "busy" and v}
    return ", ".join(f"{k} {v}" for k, v in sorted(keep.items(), key=lambda kv: -kv[1])) or "-"


out = []
w = out.append

w("# Tri-Queue cycle-model results\n")
w("Generated by `model/bench.py`. Every run is also checked bit-exact against numpy.")
w("Defaults: 64 int8 MACs, 128-bit read port, separate write port, memory latency 2, "
  "FIFO depth 8, MAC command queue 4, stream command queue 2.\n")

# 1. headline claims
w("## 1. Spec claims\n")
w("| Claim | Spec predicts | Simulated | Verdict |")
w("| --- | --- | --- | --- |")
s = gemm(64, 64, 64)
w(f"| 64³ cycles (separate write port) | ≈ 4,120 (99.4%) | {s.cycles:,} ({pct(s.utilization)}) | "
  f"{'✅' if s.utilization > 0.99 else '❌'} |")
w(f"| 64³ dynamic instructions | ≈ 2.3k (2,317) | {s.instructions:,} | {'✅' if s.instructions == 2317 else '❌'} |")
w(f"| 64³ SRAM reads | 64 KB | {s.read_bytes // 1024} KB | {'✅' if s.read_bytes == 65536 else '❌'} |")
w(f"| 64³ C writes | 16 KB (int32) | {s.write_bytes // 1024} KB | {'✅' if s.write_bytes == 16384 else '❌'} |")
w(f"| Program size | 10 B kernel + 40 B CFG | {s.program_bytes - 40} B kernel + 40 B CFG | "
  f"{'✅' if s.program_bytes == 50 else '❌'} |")
sh = gemm(64, 64, 64, Params(shared_port=True))
w(f"| 64³ shared read/write port | ≈ 80% | {sh.cycles:,} ({pct(sh.utilization)}) | "
  f"{'✅' if abs(sh.utilization - 0.80) < 0.02 else '❌'} |")
for m, n, shape, pred in [(64, 4, "8×4×2", 0.667), (4, 64, "4×8×2", 0.667), (4, 4, "4×4×4", 0.50)]:
    e = gemm(m, n, 1024)
    w(f"| Edge-tile shape {shape} ({m}×{n}×1024) | {pct(pred)} | {pct(e.utilization)} | "
      f"{'✅' if abs(e.utilization - pred) < 0.02 else '❌'} |")
w("")

# 2. size sweep
w("## 2. Size sweep\n")
w("| M×N×K | Cycles | Ideal | Utilization | Instr | Shapes used | MAC stall cycles |")
w("| --- | --- | --- | --- | --- | --- | --- |")
for m, n, k in shapes("model"):
    s = gemm(m, n, k)
    shapes = ", ".join(f"{k_} ×{v}" for k_, v in s.mac_ops.items())
    w(f"| {m}×{n}×{k} | {s.cycles:,} | {s.ideal_cycles:,} | {pct(s.utilization)} | {s.instructions:,} | "
      f"{shapes} | {stalls(s)} |")
w("")

# 3. drain-hiding condition K >= 16
w("## 3. Drain hiding vs K (64×64×K)\n")
w("Spec claim: the 16-cycle drain hides under compute only when K ≥ 16.\n")
w("| K | Cycles | Utilization | wait_drain cycles |")
w("| --- | --- | --- | --- |")
for k in (8, 16, 24, 32, 64, 128):
    s = gemm(64, 64, k)
    w(f"| {k} | {s.cycles:,} | {pct(s.utilization)} | {s.mac_state.get('wait_drain', 0)} |")
w("")

# 4. MAC command queue depth
w("## 4. MAC command queue depth (64³)\n")
w("| Depth | Cycles | Utilization | wait_cmd | front-end stalls |")
w("| --- | --- | --- | --- | --- |")
for dpt in (1, 2, 3, 4, 8):
    s = gemm(64, 64, 64, Params(mac_queue_depth=dpt))
    w(f"| {dpt} | {s.cycles:,} | {pct(s.utilization)} | {s.mac_state.get('wait_cmd', 0)} | "
      f"{dict(s.front_stall) or '-'} |")
w("")

# 5. FIFO depth x memory latency
w("## 5. Operand FIFO depth vs SRAM latency (128³, utilization)\n")
lat = (1, 2, 4, 8, 16, 32)
w("| FIFO depth \\ latency | " + " | ".join(str(x) for x in lat) + " |")
w("| --- |" + " --- |" * len(lat))
for depth in (2, 4, 8, 16, 32):
    row = [pct(gemm(128, 128, 128, Params(fifo_depth=depth, mem_latency=L)).utilization) for L in lat]
    w(f"| {depth} | " + " | ".join(row) + " |")
w("")

text = "\n".join(out)
Path(__file__).with_name("results.md").write_text(text + "\n")
print(text)
