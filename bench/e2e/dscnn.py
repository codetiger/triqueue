"""End-to-end DS-CNN (MLPerf Tiny keyword spotting, int8) on the Tri-Queue cycle model.

The convolutions and the fully connected layer run on the core: the host builds A (im2col for the
10x4 convolution, the layer input itself for the 1x1 ones) and packs it, and the core does the GEMM
and the TFLite epilogue (MODE[9]) from a parameter table built offline with the packed weights.
Depthwise convolutions, the average pool and the reshape run on the host (spec: depthwise is out
of scope for the outer-product engine). Each layer consumes the previous layer's output as
computed here, and every tensor is checked against the TFLite interpreter's (dscnn_golden.npz,
from export_dscnn.py), bit for bit. Softmax is left to the host; its input is checked.

    python3 bench/e2e/dscnn.py            # rewrites bench/e2e/results.md (~30 s)
"""
import argparse
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parents[1] / "model"))
import tflite_ref as tr  # noqa: E402
from tri_queue.core import Params, run_gemm  # noqa: E402
from tri_queue.packing import kp, pack_a  # noqa: E402

ENGINE = ("CONV_2D", "FULLY_CONNECTED")
TILES = (8, 4)


def walk_cols(m: int, tile: int) -> bool:
    """The driver's choice (sw/tq.c tq_layer_prepare): column walk with more than one tile row."""
    return m > tile


def run(net: tr.Net, seed: int, tile: int):
    """Runs one input through the network. Returns (rows, mismatches): one row per op."""
    x = net.golden(seed, net.inputs[0])
    rows, bad = [], []
    for k, op in enumerate(net.ops):
        o = op["outputs"][0]
        row = dict(idx=k, kind=op["kind"])
        if op["kind"] in ENGINE:
            g = tr.lower(net, op, x)
            m, kk = g.a.shape
            n = g.b.shape[1]
            p = Params(tile=tile, out_bytes=1, out_shift=0, walk_cols=walk_cols(m, tile))
            c, s = run_gemm(g.a, g.b, p, epi=g.epi)
            assert s.error == 0
            if not np.array_equal(c, tr.gemm_reference(g)):
                bad.append((k, "core vs requant reference"))
            y = c.reshape(g.out_shape)
            row.update(where="core", m=m, n=n, k=kk, macs=m * n * kk, cycles=s.cycles,
                       util=m * n * kk / (s.cycles * tile * tile), walk="cols" if p.walk_cols else "rows",
                       host_bytes=g.im2col_bytes + len(pack_a(g.a, kp(kk), tile)), host_macs=0,
                       reads=s.read_vectors)
        elif op["kind"] == "DEPTHWISE_CONV_2D":
            y = tr.depthwise(net, op, x)
            kh, kw = net.tensors[op["inputs"][1]]["shape"][1:3]
            row.update(where="host", macs=int(np.prod(y.shape)) * kh * kw, host_macs=int(np.prod(y.shape)) * kh * kw,
                       host_bytes=0)
        elif op["kind"] == "AVERAGE_POOL_2D":
            y = tr.average_pool(net, op, x)
            row.update(where="host", macs=0, host_macs=0, host_bytes=int(np.prod(x.shape)))
        elif op["kind"] == "RESHAPE":
            y = x.reshape(net.tensors[o]["shape"])
            row.update(where="host", macs=0, host_macs=0, host_bytes=0)
        elif op["kind"] == "SOFTMAX":
            rows.append(dict(row, where="host", macs=0, host_macs=0, host_bytes=0))
            break
        else:
            raise NotImplementedError(op["kind"])
        if not np.array_equal(y, net.golden(seed, o)):
            bad.append((k, f"{op['kind']} vs TFLite"))
        rows.append(row)
        x = y
    return rows, bad


LABEL = {"CONV_2D": "conv", "DEPTHWISE_CONV_2D": "depthwise", "AVERAGE_POOL_2D": "average pool",
         "RESHAPE": "reshape", "FULLY_CONNECTED": "fully connected", "SOFTMAX": "softmax"}


def report(net: tr.Net) -> str:
    out = ["<!-- Generated by bench/e2e/dscnn.py; do not edit. -->", "",
           "# End-to-end DS-CNN (keyword spotting, int8)", "",
           "MLPerf Tiny's DS-CNN (`kws_ref_model.tflite`, int8 per-channel) run layer by layer: "
           "convolutions and the fully connected layer on the Tri-Queue cycle model (host im2col and "
           "packing of A, then GEMM + TFLite epilogue, `MODE[9]`), depthwise convolutions and the "
           "average pool on the host. Each layer consumes this run's previous output, and every "
           "tensor is compared with the TFLite interpreter's (reference kernels) for "
           f"{len(net.seeds)} random int8 inputs.", ""]
    for tile in TILES:
        results = [run(net, s, tile) for s in net.seeds]
        bad = [b for _, bb in results for b in bb]
        rows = results[0][0]
        out += [f"## T = {tile} ({tile * tile} MACs/cycle), default build", "",
                f"Bit-exact with TFLite: **{'yes' if not bad else 'NO: ' + str(bad)}** "
                f"({sum(len(r) for r, _ in results)} tensors over {len(net.seeds)} inputs).", "",
                "| # | Op | Runs on | GEMM m × n × k | MACs | Walk | Core cycles | Utilization | Host bytes (im2col + pack A) | Host MACs |",
                "| --- | --- | --- | --- | ---: | --- | ---: | ---: | ---: | ---: |"]
        for r in rows:
            core = r["where"] == "core"
            out.append(f"| {r['idx']} | {LABEL[r['kind']]} | {r['where']} | "
                       + (f"{r['m']} × {r['n']} × {r['k']}" if core else "–")
                       + f" | {r['macs']:,} | {r.get('walk', '–')} | "
                       + (f"{r['cycles']:,} | {100 * r['util']:.1f}%" if core else "– | –")
                       + f" | {r['host_bytes']:,} | {r['host_macs']:,} |")
        cyc = sum(r.get("cycles", 0) for r in rows)
        cmacs = sum(r["macs"] for r in rows if r["where"] == "core")
        hb = sum(r["host_bytes"] for r in rows)
        hm = sum(r["host_macs"] for r in rows)
        out += [f"| | **total** | | | {cmacs + hm:,} | | **{cyc:,}** | "
                f"**{100 * cmacs / (cyc * tile * tile):.1f}%** | {hb:,} | {hm:,} |", "",
                f"The core does {100 * cmacs / (cmacs + hm):.1f}% of the network's MACs in {cyc:,} cycles. "
                f"Per inference the host writes {hb:,} bytes (im2col and A packing; weights, B packing and "
                f"the epilogue tables are offline) and does {hm:,} depthwise MACs. At an assumed scalar "
                f"host rate of 1 byte and 1 MAC per cycle that is about {hb + hm:,} host cycles, "
                f"{(hb + hm) / cyc:.1f}× the core's: on this network the depthwise layers, not the GEMMs, "
                f"bound a single-issue host, which is the case for running depthwise on a vector unit "
                f"or in the core.", ""]
    out += ["Inputs are uniform random int8 (`export_dscnn.py`, seeds "
            + ", ".join(str(s) for s in net.seeds) + "), not audio features: bit-exactness does not "
            "depend on the data, and the cycle counts depend only on the shapes. The model's "
            "`mem_latency`, FIFO and queue depths are the defaults; no panel buffer. Host costs are "
            "counts, not a host simulation.", ""]
    return "\n".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", type=Path, default=HERE / "results.md")
    args = ap.parse_args(argv)
    text = report(tr.load())
    args.out.write_text(text)
    print(text)
    if "NO:" in text:
        raise SystemExit("mismatch against TFLite")


if __name__ == "__main__":
    main()
