"""Write the C header tq_gemm_test.c checks against: the 64 x 64 x 64 int32 product of the int8
A and B that the program generates with its LCG, computed here with numpy, so that the simulated
Rocket core does not spend millions of cycles on a reference GEMM in software.

  python3 bench/soc/chipyard/export_gemm.py build/soc/TriQueueRocketConfig/tq_gemm_ref.h
"""
import sys
from pathlib import Path

import numpy as np

M = N = K = 64


def lcg_int8(count, state=12345):
    """tq_gemm_test.c's rnd(): state = state * 1103515245 + 12345 (mod 2^32), int8(state >> 16)."""
    out = np.empty(count, dtype=np.int8)
    for i in range(count):
        state = (state * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = np.int8(np.uint8((state >> 16) & 0xFF).view(np.int8))
    return out


def main(out):
    v = lcg_int8(M * K + K * N)
    a = v[:M * K].reshape(M, K).astype(np.int32)
    b = v[M * K:].reshape(K, N).astype(np.int32)
    ref = a @ b
    rows = ["{" + ", ".join(str(int(x)) for x in row) + "}" for row in ref]
    Path(out).write_text("// Generated by bench/soc/chipyard/export_gemm.py.\n"
                         "// SPDX-License-Identifier: Apache-2.0\n"
                         f"static const int32_t ref[{M}][{N}] = {{\n    " + ",\n    ".join(rows) + "\n};\n")


if __name__ == "__main__":
    main(sys.argv[1])
