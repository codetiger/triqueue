"""Write the C header tq_layer_test.c runs on the Chipyard SoC: real MLPerf Tiny layers (TFLite
weights, quantization and activations from bench/e2e/<net>_golden.npz) with TFLite's own output
tensor as the expected result.

  python3 bench/soc/chipyard/export_layers.py build/soc/TriQueueRocketConfig/tq_layers.h

Layers: DS-CNN op 2 (1x1 CONV_2D + ReLU, 125 x 64 x 64, TFLite's double rounding, column walk) and
the ResNet-8 classifier, op 14 (FULLY_CONNECTED, 1 x 10 x 64, single rounding, MODE[10]). The inputs
are chosen so that both are discriminating: the other rounding form changes outputs of each layer
(the script prints how many).
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "e2e"))
import tflite_ref  # noqa: E402

# (network, op index, golden input)
LAYERS = (("dscnn", 2, 1), ("resnet8", 14, 2))


def array(ctype, name, values):
    vals = [str(int(v)) for v in np.asarray(values).reshape(-1)]
    rows = [", ".join(vals[i:i + 24]) for i in range(0, len(vals), 24)]
    return f"static const {ctype} {name}[{len(vals)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main(out):
    text = ["// Generated by bench/soc/chipyard/export_layers.py from bench/e2e/*_golden.npz.\n",
            "// SPDX-License-Identifier: Apache-2.0\n"]
    entries = []
    for name, op_i, seed in LAYERS:
        net = tflite_ref.load(name)
        op = net.ops[op_i]
        g = tflite_ref.lower(net, op, net.golden(seed, op["inputs"][0]))
        m, k = g.a.shape
        n = g.b.shape[1]
        gold = net.golden(seed, op["outputs"][0]).reshape(m, n)
        e, p = g.epi, f"{name}_op{op_i}"
        assert np.array_equal(tflite_ref.gemm_reference(g), gold), f"{p}: lowering != TFLite"
        other = "double" if e["rounding"] == "single" else "single"
        diff = int((tflite_ref.gemm_reference(g, other) != gold).sum())
        assert diff, f"{p}: input {seed} does not tell the two roundings apart"
        print(f"{p}: {m} x {n} x {k}, {e['rounding']} rounding; {other} rounding changes {diff} outputs")
        text += [array("int8_t", f"{p}_a", g.a), array("int8_t", f"{p}_b", g.b),
                 array("int32_t", f"{p}_bias", e["bias"]), array("int32_t", f"{p}_m0", e["m0"]),
                 array("int32_t", f"{p}_shift", e["shift"]), array("int8_t", f"{p}_gold", gold)]
        rounding = "TQ_ROUND_SINGLE" if e["rounding"] == "single" else "TQ_ROUND_DOUBLE"
        entries.append(f'    {{"{name} op {op_i} {op["kind"]}", {m}u, {n}u, {k}u, {p}_a, {p}_b, {p}_gold,\n'
                       f'     {{{p}_bias, {p}_m0, {p}_shift, {int(e["zp"])}, {int(e["act_min"])}, '
                       f'{int(e["act_max"])}, {rounding}}}}},\n')
    text.append("static const tq_soc_layer layers[] = {\n" + "".join(entries) + "};\n")
    Path(out).write_text("".join(text))


if __name__ == "__main__":
    main(sys.argv[1])
