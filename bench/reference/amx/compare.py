"""Compare measured Apple AMX utilization (M2 Pro) with the Tri-Queue cycle model.

Run after amx_peak / amx_gemm / sgemm_sweep have written their CSVs:
    python3 compare.py          (writes results.md)
"""
import csv
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
ROOT = HERE.resolve().parents[2]
sys.path.insert(0, str(ROOT / "model"))
sys.path.insert(0, str(ROOT / "bench" / "workloads"))
from tri_queue.core import run_gemm, reference  # noqa: E402
from workloads import shapes  # noqa: E402


def load(name):
    with open(HERE / name) as f:
        return list(csv.DictReader(f))


peak = load("peak.csv")
p1 = max(float(r["macs_per_s"]) for r in peak if r["kind"] == "fma32" and r["threads"] == "1")
op_rate = max(float(r["ops_per_s"]) for r in peak if r["kind"] == "fma32" and r["threads"] == "1")
pall = max(float(r["macs_per_s"]) for r in peak if r["kind"] == "fma32")
key = lambda r: (int(r["m"]), int(r["n"]), int(r["k"]))  # noqa: E731
hand = {key(r): float(r["macs_per_s"]) for r in load("amx_gemm.csv")}
hand_t = {key(r): float(r["sec_per_call"]) for r in load("amx_gemm.csv")}
acc1 = {key(r): float(r["macs_per_s"]) for r in load("sgemm_1t.csv")}
accm = {key(r): float(r["macs_per_s"]) for r in load("sgemm_mt.csv")}

rng = np.random.default_rng(0)
_sim_cache = {}


def tq(m, n, k):
    if (m, n, k) not in _sim_cache:
        a = rng.integers(-128, 128, (m, k)).astype(np.int8)
        b = rng.integers(-128, 128, (k, n)).astype(np.int8)
        c, s = run_gemm(a, b)
        assert np.array_equal(c, reference(a, b))
        _sim_cache[(m, n, k)] = s.utilization
    return _sim_cache[(m, n, k)]


def pct(x):
    return "–" if x is None else f"{100 * x:.1f}%"


out = []
w = out.append
w("# Apple AMX (M2 Pro) vs Tri-Queue: utilization\n")
w("Generated by `bench/reference/amx/compare.py` from measurements on this machine. AMX is undocumented; "
  "the kernels use the encodings from github.com/corsix/amx.\n")

w("## Measured AMX peak\n")
w("| Measurement | Value |")
w("| --- | --- |")
w(f"| fp32 outer products per second, 1 thread (4 independent Z tiles) | {op_rate / 1e9:.2f} G/s (≈ 1 per cycle) |")
w(f"| fp32 peak, one P-cluster AMX unit | **{p1 / 1e12:.3f} TMAC/s** ({2 * p1 / 1e12:.2f} TFLOPS) |")
w(f"| fp32 peak, all AMX units (2 P-clusters + E-cluster) | {pall / 1e12:.2f} TMAC/s |")
lat = [float(r["ops_per_s"]) for r in peak if r["kind"] == "fma32" and r["threads"] == "1" and r["chains"] == "1"][0]
w(f"| fma32 latency (from 1 dependent chain) | ≈ {op_rate / lat:.1f} ops |")
w("")

# Linear fit of the hand kernel on 64x64xK: time = tiles * (overhead + K * per_k)
ks = [8, 16, 24, 32, 128, 1024]
t = np.array([hand_t[(64, 64, k)] for k in ks])
slope, icpt = np.polyfit(ks, t, 1)
tiles = 4
cyc = 1 / op_rate
per_k_cycles = slope / tiles / cyc
tile_over_cycles = icpt / tiles / cyc
w("## AMX hand kernel breakdown (fit over 64×64×K)\n")
w(f"- Steady state: {per_k_cycles:.2f} AMX cycles per k step for 4 fma32 → **{pct(4 / per_k_cycles)}** of peak.")
w(f"- Fixed cost per 32×32 output tile: ≈ **{tile_over_cycles:.0f} cycles**, which is the single Z accumulator's "
  "64 stores plus per-call overhead spread over the 4 tiles.")
w("- See `ablation.md` for a 3-parameter fit that separates per-call from per-tile cost.\n")

w("## Utilization by workload\n")
w("Utilization = achieved MACs/s ÷ peak of the same engine. AMX: fp32, measured; Tri-Queue: int8, cycle model.\n")
w("| M×N×K | Tri-Queue model | AMX hand kernel (pre-packed) | Accelerate sgemm, 1 thread | Accelerate sgemm, all threads |")
w("| --- | --- | --- | --- | --- |")
for m, n, k in shapes("amx"):
    sim = tq(m, n, k) if m * n * k <= 256 ** 3 else None
    h = hand.get((m, n, k))
    a1 = acc1.get((m, n, k))
    am = accm.get((m, n, k))
    w(f"| {m}×{n}×{k} | {pct(sim)} | {pct(h / p1 if h else None)} | {pct(a1 / p1 if a1 else None)} | "
      f"{pct(am / pall if am else None)} |")
w("")
w("Tri-Queue values above 256³ are not simulated (too slow in Python). The model's trend is ≈ 100%.\n")

w("## Caveats\n")
w("- **Same bytes per MAC, different reuse per element.** AMX's 32×32 fp32 tile does 16 MACs per element "
  "loaded and the Tri-Queue's 8×8 int8 tile does 4, but both read 0.25 bytes per MAC.")
w("- **Different precisions and sizes.** AMX does 256 fp32 MACs per cycle per unit, and the Tri-Queue does "
  "64 int8 MACs. Only utilization is compared, not throughput or efficiency.")
w("- **Model vs silicon.** The Tri-Queue numbers assume ideal SRAM with fixed latency. AMX numbers are "
  "real hardware fed from L1/L2 caches, with OS noise and clock variation.")
w("- **Accelerate includes CPU-side packing and call overhead,** about 0.4 µs per call, which dominates "
  "small GEMMs. The hand kernel and the Tri-Queue model both exclude packing.")
w("- **Accelerate only goes multi-threaded from about 512³.** Below that, the all-threads column is low "
  "because its denominator is every AMX unit on the chip.")
w("- **The hand kernel is straightforward, not expert-tuned.** Z holds exactly one 32×32 fp32 tile, so its "
  "store can't overlap compute unless the tile shrinks (for example to two 32×16 halves taking turns), "
  "which lowers reuse. A tuned kernel could narrow the small-size gap.")
w("- **GEMV is memory-bound everywhere.** For example, 1×4096×4096 in Accelerate runs at "
  f"{acc1[(1, 4096, 4096)] / 1e9:.1f} GMAC/s, which is about {acc1[(1, 4096, 4096)] * 4 / 1e9:.0f} GB/s "
  "of fp32 matrix streaming from DRAM.")

text = "\n".join(out)
(HERE / "results.md").write_text(text + "\n")
print(text)
