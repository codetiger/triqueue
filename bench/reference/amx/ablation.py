"""Precision-independent test of the double-bank claim.

1. Ablation: the Tri-Queue simulator with 1 vs 2 accumulator banks (same int8 engine, same model).
2. One first-order model for both engines:
       cycles = F + tiles * (K * c_k + D_exposed)
   F = fixed per-call cost, c_k = cycles per k step of one output tile,
   D_exposed = accumulator-drain cycles per tile that compute cannot overlap.
   - Tri-Queue: parameters come from the design (not fitted) and are checked against the simulator.
   - AMX: c_k and the per-tile cost are fitted on the 64x64xK sweep only, then used to predict
     the square sizes, which were held out of the fit.
Writes ablation.md. Needs peak.csv and amx_gemm.csv (see README).
"""
import csv
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
ROOT = HERE.resolve().parents[2]
sys.path.insert(0, str(ROOT / "model"))
from tri_queue.core import run_gemm, reference, Params  # noqa: E402

rng = np.random.default_rng(0)


def sim(m, n, k, banks):
    a = rng.integers(-128, 128, (m, k)).astype(np.int8)
    b = rng.integers(-128, 128, (k, n)).astype(np.int8)
    c, s = run_gemm(a, b, Params(banks=banks))
    assert np.array_equal(c, reference(a, b))
    return s


def load(name):
    with open(HERE / name) as f:
        return list(csv.DictReader(f))


def pct(x):
    return f"{100 * x:.1f}%"


out = []
w = out.append
w("# Accumulator double-banking: ablation and calibration\n")
w("Generated by `bench/reference/amx/ablation.py`. Utilization = useful MACs ÷ (peak MACs/cycle × cycles).\n")

# ---------------------------------------------------------------- 1. Tri-Queue ablation
TQ_F, TQ_DRAIN = 34, 16 + 2 + 1      # fixed cost; 16 writes + MAC pipe + CPA (design parameters)
TQ_DRAIN_THRU = 16 + 1               # 2 banks: drain of tile t overlaps tile t+1, so only writes + CPA bound it


def tq_model(m, n, k, banks):
    kpad = -(-k // 8) * 8
    tiles = (m // 8) * (n // 8)
    exposed = TQ_DRAIN if banks == 1 else max(0, TQ_DRAIN_THRU - kpad)
    return TQ_F + tiles * (kpad + exposed)


w("## 1. Tri-Queue simulator: one bank vs two\n")
w("Same int8 engine, same simulator. Only the number of SC banks changes. "
  "The model uses design parameters, not a fit: F = 34; 1 bank exposes the full drain "
  "(16 writes + 2 MAC pipe + 1 CPA = 19); 2 banks only stall if Kp < 16 writes + 1 CPA.\n")
w("| M×N×K | 2 banks (sim) | 1 bank (sim) | 1 bank: exposed drain / tile | Model error, 2 banks | Model error, 1 bank |")
w("| --- | --- | --- | --- | --- | --- |")
tq_rows = [(32, 32, 32), (64, 64, 64), (128, 128, 128), (256, 256, 256),
           (64, 64, 8), (64, 64, 16), (64, 64, 32), (64, 64, 128), (64, 64, 1024)]
worst = 0
for m, n, k in tq_rows:
    s2, s1 = sim(m, n, k, 2), sim(m, n, k, 1)
    tiles = (m // 8) * (n // 8)
    e2 = s2.cycles / tq_model(m, n, k, 2) - 1
    e1 = s1.cycles / tq_model(m, n, k, 1) - 1
    worst = max(worst, abs(e1), abs(e2))
    w(f"| {m}×{n}×{k} | {pct(s2.utilization)} | {pct(s1.utilization)} | "
      f"{(s1.cycles - s2.cycles) / tiles:.1f} cycles | {100 * e2:+.1f}% | {100 * e1:+.1f}% |")
w(f"\nWorst model error: {100 * worst:.1f}%.\n")

# ---------------------------------------------------------------- 2. AMX calibration
peak = load("peak.csv")
op_rate = max(float(r["ops_per_s"]) for r in peak if r["kind"] == "fma32" and r["threads"] == "1")
cyc = 1 / op_rate                                    # AMX cycle, from the peak microbenchmark
hand = {(int(r["m"]), int(r["n"]), int(r["k"])): float(r["sec_per_call"]) for r in load("amx_gemm.csv")}

# Fit on the K sweeps of 3 tile counts (1, 4, 16 tiles); square sizes are held out.
fit = [(32, 32, k) for k in (8, 16, 128, 1024, 4096)] + [(64, 64, k) for k in (8, 16, 24, 32, 128, 1024)] \
    + [(128, 128, k) for k in (8, 16, 32, 1024)]
X = np.array([[1, (m // 32) * (n // 32), (m // 32) * (n // 32) * k] for m, n, k in fit], float)
y = np.array([hand[f] for f in fit]) / cyc
amx_F, amx_tile, amx_ck = np.linalg.lstsq(X, y, rcond=None)[0]


def amx_model(m, n, k):
    return amx_F + (m // 32) * (n // 32) * (k * amx_ck + amx_tile)


w("## 2. Same model calibrated on Apple AMX (M2 Pro, measured)\n")
w(f"Fitted by least squares on the K sweeps at 1, 4 and 16 output tiles ({len(fit)} runs): "
  f"**c_k = {amx_ck:.2f} cycles** per k step (ideal 4: 4 fma32 of 16×16), "
  f"**D = {amx_tile:.0f} cycles** per 32×32 tile (storing the single Z accumulator, which can't overlap compute), "
  f"and **F = {amx_F:.0f} cycles** per call (function call, AMX set-up, timing loop).\n")
w("Held-out prediction (square sizes were not used in the fit):\n")
w("| M×N×K | Measured | Model | Error |")
w("| --- | --- | --- | --- |")
for sz in (32, 64, 128, 256, 512):
    meas = hand[(sz, sz, sz)] / cyc
    pred = amx_model(sz, sz, sz)
    w(f"| {sz}³ | {meas:,.0f} cycles ({pct(sz ** 3 / 256 / meas)}) | {pred:,.0f} cycles | {100 * (meas / pred - 1):+.1f}% |")
w("")

# ---------------------------------------------------------------- 3. normalized comparison
w("## 3. The comparison that does not depend on precision\n")
w("Express each engine's exposed drain in units of its own k step. Then utilization on a tile "
  "depends only on K: util ≈ K / (K + D/c_k).\n")
amx_dk = amx_tile / amx_ck
tq_dk = TQ_DRAIN / 1.0
w("| Engine | Cycles per k step | Exposed drain per tile | Drain in k steps | K at which utilization = 50% |")
w("| --- | --- | --- | --- | --- |")
w(f"| AMX (1 accumulator, measured) | {amx_ck:.2f} | {amx_tile:.0f} | {amx_dk:.0f} | {amx_dk:.0f} |")
w(f"| Tri-Queue, 1 bank (sim) | 1 | {TQ_DRAIN} | {tq_dk:.0f} | {tq_dk:.0f} |")
w(f"| Tri-Queue, 2 banks (sim) | 1 | 0 once Kp ≥ 24 (1 cycle at Kp = 16) | 0 | – |")
w("")
w("| K (64×64×K) | AMX measured | Tri-Queue 1 bank | Tri-Queue 2 banks |")
w("| --- | --- | --- | --- |")
for k in (8, 16, 32, 128, 1024):
    amx_u = 64 * 64 * k / 256 / (hand[(64, 64, k)] / cyc)
    w(f"| {k} | {pct(amx_u)} | {pct(sim(64, 64, k, 1).utilization)} | {pct(sim(64, 64, k, 2).utilization)} |")
w("")
w("**Reading:** measured in its own k steps, AMX's exposed drain (≈ 16) is about the same as a "
  "single-bank Tri-Queue's (19), and both lose about half their throughput at K ≈ 16–19. The same "
  "one-line model fits both within a few percent. Adding the second bank removes the loss in the "
  "simulator. The int8 vs fp32 difference doesn't enter any of these numbers. The remaining gap at "
  "large K (AMX 91% against the Tri-Queue's 98–100%) is AMX's ≈ 7% steady-state issue overhead "
  "(4.29 against 4 cycles per k step), which isn't about the accumulator.\n")

# ---------------------------------------------------------------- 4. why AMX can't just double-bank
lat = [float(r["ops_per_s"]) for r in peak if r["kind"] == "fma32" and r["threads"] == "1" and r["chains"] == "1"][0]
w("## 4. Why AMX can't simply add a second bank in software\n")
w(f"- Measured fma32 latency ≈ {op_rate / lat:.0f} ops, so full rate needs 4 independent accumulators.")
w("- Z holds exactly 4 fp32 16×16 tiles (4 KB). A 32×32 tile uses all of them.")
w("- Splitting Z into two 32×16 halves that take turns leaves 2 chains per half, which caps compute at "
  f"about 50% (the 2-chain peak measurement: {pct(2 * lat / op_rate)}).")
w("- This limit comes from floating point: the accumulate latency forces 4 accumulators. The Tri-Queue's "
  "1-cycle carry-save int accumulate needs only one per tile, which leaves room for a second bank. An fp32 "
  "Tri-Queue would face the same limit as AMX.\n")

text = "\n".join(out)
(HERE / "ablation.md").write_text(text + "\n")
print(text)
