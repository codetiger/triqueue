"""Run tq_top through OpenROAD-flow-scripts (ORFS).

    python3 flow/ppa.py run sky130hd t8_csa              # full flow, RTL to routed layout
    python3 flow/ppa.py run sky130hd t8_csa --to synth   # stop after a stage
    python3 flow/ppa.py run asap7 t8_cpa --period 900    # override the clock period
    python3 flow/ppa.py --docker run sky130hd t8_csa     # the pinned Docker image instead
    python3 flow/ppa.py sweep asap7 t8_cpa 950 900 850   # one run per period, then a closure table
    python3 flow/ppa.py list                             # platforms and configurations

The reference flow is a native ORFS build at ORFS_COMMIT in ORFS_HOME (see flow/README.md);
its runs work in build/orfs_native/<platform>/<config>/ (config.mk, logs, reports, results)
and stop before the GDS, which PPA does not need. --docker runs the same commit's image
(ORFS_IMAGE, amd64) in build/orfs_docker/...: close to the native results, not bit-identical.
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORFS_IMAGE = "openroad/orfs:26Q4-272-gd0e5b3c13"
ORFS_COMMIT = "d0e5b3c13"               # the image's ORFS commit; a native checkout must match
ORFS_HOME = Path(os.environ.get("ORFS_HOME", "~/Development/OpenROAD-flow-scripts")).expanduser()
DOCKER_WORK = "/work"                   # ROOT is mounted here inside the container

# name: tq_top parameters. CLK_GATE defaults to 1 (clock gates on, tq_cg). The reference
# configurations size the queues for the reference SRAMs (1-cycle read, model mem_latency 2):
# FIFO depth 4 and MAC queue depth 3 lose no cycle up to an SRAM latency of 3 in the cycle
# model; the RTL defaults (8 and 4) hide up to 8 cycles.
Q = dict(FIFO_DEPTH=4, MACQ_DEPTH=3)
CONFIGS = {
    "t8_csa":      dict(T=8, ACC_FORM=0, **Q),
    "t8_cpa":      dict(T=8, ACC_FORM=1, **Q),
    "t8_cpa_nocg": dict(T=8, ACC_FORM=1, CLK_GATE=0, **Q),
    "t8_shared":   dict(T=8, ACC_FORM=1, SHARED_PORT=1, **Q),
    # A panel buffer (spec 10.9, decision 0011): its area and energy against the reads it saves
    "t8_panel1k":  dict(T=8, ACC_FORM=1, PANEL_BYTES=1024, **Q),
    "t8_panel4k":  dict(T=8, ACC_FORM=1, PANEL_BYTES=4096, **Q),
    # one MAC stage (no product register): fewer flops, a longer path (sky130 at 100 MHz)
    "t8_mac1":     dict(T=8, ACC_FORM=1, MAC_PIPE=1, **Q),
    "t16_csa":     dict(T=16, ACC_FORM=0, **Q),
    "t16_cpa":     dict(T=16, ACC_FORM=1, **Q),
    "t32_csa":     dict(T=32, ACC_FORM=0, **Q),
    "t32_cpa":     dict(T=32, ACC_FORM=1, **Q),
}

# Reference runs whose clock differs from the platform's: (platform, config) -> period. A config
# that cannot close the platform clock is recorded at one it closes, so its energy is measured
# at a clock it really runs at (found with `ppa.py sweep`).
PERIOD_OVERRIDE = {
    ("asap7", "t16_cpa"): 1350,
}

# name: clock period (platform time unit), floorplan utilization (%), Docker thread cap, extra
# ORFS variables. The detailed router's memory grows with its thread count: asap7 at T = 8 needs
# over 12 GB with 8 threads, more than a 16 GB laptop's Docker VM has.
PLATFORMS = {
    "sky130hd":   dict(period=10.0, unit="ns", util=40, max_jobs=8, extra={}),
    "ihp-sg13g2": dict(period=8.0,  unit="ns", util=40, max_jobs=8, extra={}),
    "asap7":      dict(period=1000, unit="ps", util=45, max_jobs=3, extra={}),
}

STAGES = ("synth", "floorplan", "place", "cts", "route", "finish")


def base(native):
    """Path of the repository root as the flow sees it."""
    return str(ROOT) if native else DOCKER_WORK


def config_mk(platform, config, period, native=False, nick=None):
    WORK = base(native)
    p = PLATFORMS[platform]
    files = [f"{WORK}/{line}" for line in (ROOT / "rtl" / "files.f").read_text().split()]
    params = " ".join(f"{k} {v}" for k, v in CONFIGS[config].items())
    lines = [
        "# Generated by flow/ppa.py. Do not edit.",
        "export DESIGN_NAME        = tq_top",
        f"export DESIGN_NICKNAME    = tq_{nick or config}",
        f"export PLATFORM           = {platform}",
        f"export VERILOG_FILES      = {' '.join(files)}",
        # OPENROAD_CLKGATE maps tq_icg to the platform's clock-gating cell (rtl/common/tq_icg.sv)
        "export VERILOG_DEFINES    = -DSYNTHESIS -DOPENROAD_CLKGATE",
        f"export VERILOG_TOP_PARAMS = {params}",
        f"export SDC_FILE           = {WORK}/flow/constraint.sdc",
        f"export TQ_CLK_PERIOD      = {period}",
        f"export CORE_UTILIZATION   = {p['util']}",
    ]
    lines += [f"export {k} = {v}" for k, v in p["extra"].items()]
    return "\n".join(lines) + "\n"


def work_dir(platform, config, native=False):
    return Path("build") / ("orfs_native" if native else "orfs_docker") / platform / config


def reference_period(platform, config):
    return PERIOD_OVERRIDE.get((platform, config), PLATFORMS[platform]["period"])


def sweep_name(config, period):
    """Run name of one sweep point: its own work directory, never a reference run."""
    return f"{config}_p{period:g}"


def check_native():
    head = subprocess.run(["git", "-C", str(ORFS_HOME), "rev-parse", "--short=9", "HEAD"],
                          capture_output=True, text=True).stdout.strip()
    if head != ORFS_COMMIT:
        sys.exit(f"[ppa] {ORFS_HOME} is at {head or '?'}, expected ORFS {ORFS_COMMIT}")
    for tool in ("OpenROAD/bin/openroad", "yosys/bin/yosys"):
        if not (ORFS_HOME / "tools" / "install" / tool).exists():
            sys.exit(f"[ppa] {ORFS_HOME}/tools/install/{tool} missing; build it (flow/README.md)")


def finish_targets(platform, config, native):
    """`finish` without the GDS: final netlist, SDC, SPEF and reports."""
    w = f"{base(native)}/{work_dir(platform, config, native)}"
    d = f"{platform}/tq_{config}/base"
    return f"{w}/results/{d}/6_final.v {w}/results/{d}/6_final.sdc {w}/logs/{d}/6_report.log"


def orfs_make(platform, config, target, jobs, log, env=None, native=False):
    """Run `make <target>` with ORFS for a run directory that has a config.mk."""
    rel = work_dir(platform, config, native)
    WORK = base(native)
    extra = " ".join(f"{k}={v}" for k, v in (env or {}).items())
    args = (f"DESIGN_CONFIG={WORK}/{rel}/config.mk WORK_HOME={WORK}/{rel} NUM_CORES={jobs} "
            f"{extra} {target}")
    if native:
        check_native()
        cmd = ["bash", "-c", f"source {ORFS_HOME}/env.sh > /dev/null && "
               f"gmake -C {ORFS_HOME}/flow {args}"]
    else:
        cmd = ["docker", "run", "--rm", "--platform", "linux/amd64",
               "-v", f"{ROOT}:{WORK}", ORFS_IMAGE,
               "bash", "-c", f"source /OpenROAD-flow-scripts/env.sh > /dev/null && "
               f"make -C /OpenROAD-flow-scripts/flow {args}"]
    with open(ROOT / rel / log, "w") as f:
        return subprocess.run(cmd, stdout=f, stderr=subprocess.STDOUT).returncode


def run(platform, config, period, to, jobs, native=True, name=None):
    """One flow run. `name` (default: the config) names the work directory and the ORFS design
    nickname, so sweep points never overwrite the reference run of the config."""
    name = name or config
    rel = work_dir(platform, name, native)
    (ROOT / rel).mkdir(parents=True, exist_ok=True)
    mk = ROOT / rel / "config.mk"
    text = config_mk(platform, config, period, native, nick=name)
    if not mk.exists() or mk.read_text() != text:     # an unchanged config.mk keeps make incremental
        # ORFS tracks file times, not config.mk contents: after a parameter or clock change it
        # would reuse the old netlist, so the run's outputs go and the flow starts from synthesis.
        for d in ("results", "logs", "reports", "objects", "power"):
            shutil.rmtree(ROOT / rel / d, ignore_errors=True)
        mk.write_text(text)
    if not native:                                    # the Docker VM's memory is the limit
        jobs = min(jobs, PLATFORMS[platform]["max_jobs"])
    target = finish_targets(platform, name, native) if native and to == "finish" else to
    print(f"[ppa] {platform} {name} period={period} -> {rel} ({to})", flush=True)
    rc = orfs_make(platform, name, target, jobs, "flow.log", native=native)
    print(f"[ppa] {platform} {name}: exit {rc}, log {rel}/flow.log", flush=True)
    return rc


def sweep(platform, config, periods, jobs, native=True):
    """Run the full flow at each period, then print post-route timing for each: the fastest
    period that closes (worst setup slack >= 0) is the config's Fmax by closure."""
    import json
    rows = []
    for period in periods:
        name = sweep_name(config, period)
        rc = run(platform, config, period, "finish", jobs, native, name=name)
        rpt = ROOT / work_dir(platform, name, native) / "logs" / platform / f"tq_{name}" / "base" / "6_report.json"
        if rc or not rpt.exists():
            rows.append((period, None, None))
            continue
        m = json.loads(rpt.read_text())
        unit_ps = 1000 if PLATFORMS[platform]["unit"] == "ns" else 1
        rows.append((period, m["finish__timing__setup__ws"] * unit_ps, m["finish__timing__fmax"]))
    unit = PLATFORMS[platform]["unit"]
    print(f"[ppa] sweep {platform} {config}: period ({unit}) | worst setup slack (ps) | Fmax (MHz) | closes")
    for period, ws, fmax in rows:
        if ws is None:
            print(f"  {period:g} | failed")
        else:
            print(f"  {period:g} | {ws:.0f} | {fmax / 1e6:.1f} | {'yes' if ws >= 0 else 'no'}")
    return 0 if all(ws is not None for _, ws, _ in rows) else 1


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--docker", action="store_true", help=f"use the Docker image {ORFS_IMAGE} "
                    f"instead of the native build in ORFS_HOME ({ORFS_HOME})")
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run")
    r.add_argument("platform", choices=PLATFORMS)
    r.add_argument("config", choices=CONFIGS)
    r.add_argument("--period", type=float, help="clock period in the platform's unit")
    r.add_argument("--to", choices=STAGES, default="finish")
    r.add_argument("--jobs", type=int, default=os.cpu_count())
    sw = sub.add_parser("sweep")
    sw.add_argument("platform", choices=PLATFORMS)
    sw.add_argument("config", choices=CONFIGS)
    sw.add_argument("periods", type=float, nargs="+", help="clock periods in the platform's unit")
    sw.add_argument("--jobs", type=int, default=os.cpu_count())
    sub.add_parser("list")
    a = ap.parse_args()
    if a.cmd == "list":
        for k, v in PLATFORMS.items():
            print(f"{k:12s} period {v['period']} {v['unit']}, utilization {v['util']}%")
        for k, v in CONFIGS.items():
            print(f"{k:12s} {v}")
        return 0
    if a.cmd == "sweep":
        periods = [int(x) if float(x).is_integer() else x for x in a.periods]
        return sweep(a.platform, a.config, periods, a.jobs, native=not a.docker)
    period = a.period if a.period is not None else reference_period(a.platform, a.config)
    if isinstance(period, float) and period.is_integer():
        period = int(period)
    return run(a.platform, a.config, period, a.to, a.jobs, native=not a.docker)


if __name__ == "__main__":
    sys.exit(main())
